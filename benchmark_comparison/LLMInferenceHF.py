def generate_batch(batch):
    start = time.perf_counter()
    prompts = batch["prompt"]
    inputs = tokenizer(prompts, return_tensors = "pt", padding = True, truncation = True)
    inputs = {k: v.to(model.device) for k, v in inputs.items()}

    outputs = model.generate(
        **inputs,
        max_new_tokens = args.maxToken,
        return_dict_in_generate = True,  # Returns a ModelOutput object instead of a tensor
        output_logits = True,            # Includes the prediction scores (logits)
        do_sample = False # deterministic even if by default it is already false, but lets state it just in case
    )

    # We will get some objetcs, one being outputs.sequences which are the generated ids
    # We will also get outputs.logits which:
    # - it is tuple of tensors
    # - each element of the tuple is a token --> so in qwen instruct will be 2 elemnts
    # - the length of this tuple is not the whole input and output, it is just the generated tokens (different to outputs.sequence)
    # - len(outputs.logits[i]) would be the batch size
    # - so we have 1 element per token and inside of that element we have all of the samples for that batch
    # - each one of those batch sampels have the length of the vocabulary of the model, for qwen instruct that would be 151936 
    # This means that we actually want only the second to last element of that geenrated logits because if the model
    # has been successfull generating an answer, that would be the yes/no answer of the model

    answer_logits = outputs.logits[-2] # This is the only probability we want

    # Get the logits of the tokens we want
    # We cant establish it in general because depending on the model it will be different
    yes_id = tokenizer.convert_tokens_to_ids("Yes")
    no_id = tokenizer.convert_tokens_to_ids("No")

    # We get teh generated output, just the output, we dont care about the input in the sequence
    input_length = inputs["input_ids"].shape[1]
    generated_tokens = outputs.sequences[:, input_length:-1]

    # In reasoning models we have very long logits so lets move the logits to cpu
    # Move to CPU immediately to clear VRAM
    answer_logits_cpu = answer_logits.detach().float().cpu()

    # Remove from the vram the big objects so it doesnt overflow it
    del outputs
    del inputs
    # Clear gpu cache
    torch.cuda.empty_cache()
    
    # From now on we just work with cpu objects
    texts = []
    texts_trimmed = []
    probabilities_logits_yes = []
    probabilities_logits_no = []
    probabilities_interested_logits_yes = []
    probabilities_interested_logits_no = []
    for output_ids, logits_vocabulary in zip(generated_tokens, answer_logits_cpu):
        # Lets treat the output sequence
        # Use skip_special_tokens=False if Magistral, True otherwise
        text = tokenizer.decode(output_ids, skip_special_tokens = True)
        texts.append(text)
        last_token = text.split()[-1]
        texts_trimmed.append(last_token)
        
        # Now lets treat the logits so we can get probabilities
        probs = torch.nn.functional.softmax(logits_vocabulary)
        probs = probs.detach().cpu().tolist()
        probabilities_logits_yes.append(probs[yes_id])
        probabilities_logits_no.append(probs[no_id])
        probs_interested_logits = torch.nn.functional.softmax(logits_vocabulary[[yes_id, no_id]])
        probabilities_interested_logits_yes.append(probs_interested_logits[0])
        probabilities_interested_logits_no.append(probs_interested_logits[1])
    elapsed = time.perf_counter() - start
    # map with batched = True needs one value per sample, so we split the batch time evenly among them
    n_samples = len(prompts)
    elapsed_per_sample = [elapsed / n_samples] * n_samples

    return {"raw_output": texts,
            "last_word": texts_trimmed,
            "prob_yes_all_logits": probabilities_logits_yes,
            "prob_no_all_logits": probabilities_logits_no,
            "prob_yes_interested_logits": probabilities_interested_logits_yes,
            "prob_no_interested_logits": probabilities_interested_logits_no,
            "logits": answer_logits.detach().cpu(),
            "avg_elapsed_time_sample_batch": elapsed_per_sample} # batch time divided by the number of samples in the batch


## Body of the script
# load the tokenizer and the model
load_start = time.perf_counter()
model = transformers.AutoModelForCausalLM.from_pretrained(
    args.model,
    torch_dtype = "auto",
    device_map = "auto",
    local_files_only = True
)
tokenizer = transformers.AutoTokenizer.from_pretrained(args.tokenizer,
                                                       padding_side = 'left')

load_time = time.perf_counter() - load_start

# We need to separate the assistant answer so we dont give it to the model
data_eval = data.map(split_assistant)
eval_dataset = data_eval.map(formatting_prompts_func,
                             batched = True)

# Run inference

eval_dataset = eval_dataset.map(generate_batch, batched = True, batch_size = args.batch)

# We have the answers of the model and now we need to create a csv so we can get the answers
# extract the user messages of each record, it can be repetitive but still better than getting the whole
# template
user_messages = [
    next((re.search(r'## Text to classify[\n|\r\n|\n\r](.+)', m['content']).group() for m in record if m['role'] == 'user'), None)
    for record in data_eval['messages']
]

# get the pmids and numbers, just for our tracking just in case
pmids = [meta.get('pmid') for meta in data_eval['metadata']]
numbers = [meta.get('number') for meta in data_eval['metadata']]

# Get the true labels
true_labels = [record[0]['content'] for record in data_eval['gold_assistant']]

# Get th predictions
predictions = [record["raw_output"] for record in eval_dataset]
predicted_label = [record["last_word"] for record in eval_dataset]

# get the probabilities of that label
prob_all_yes = [record["prob_yes_all_logits"] for record in eval_dataset]
prob_all_no = [record["prob_no_all_logits"] for record in eval_dataset]
prob_only_2_yes = [record["prob_yes_interested_logits"] for record in eval_dataset]
prob_only_2_no = [record["prob_no_interested_logits"] for record in eval_dataset]

# get the time elapsed for each batch
elapsed_time_batch = [record["avg_elapsed_time_sample_batch"] for record in eval_dataset]

# Lets put it all together
output_df = pd.DataFrame({'pmid':pmids,
                          'number':numbers,
                          'user_mssg': user_messages,
                          'label':true_labels,
                          'generated_text':predictions,
                          'predicted_label':predicted_label,
                          'prob_yes_all_logits':prob_all_yes,
                          'prob_no_all_logits':prob_all_no,
                          'prob_yes':prob_only_2_yes,
                          'prob_no':prob_only_2_no,
                          'avg_elapsed_time_sample_batch':elapsed_time_batch})

# save it
output_df.to_csv(os.path.join(args.out, "table_output_complete.csv"), index = False)
# save the dataset
data_entire[f"{args.split}_processed"] = eval_dataset
data_entire.save_to_disk(os.path.join(args.out, f"{args.data}_processed"))

# Total time of script
total_time = time.perf_counter() - total_start

# save the load_time and total_time in a text file
with open(os.path.join(args.out, "time_tracking.txt"), "w") as f:
    f.write(f"Model load time: {load_time:.2f}s\n")
    f.write(f"Total time: {total_time:.2f}s\n")
    f.write(f"Avg time per batch for the samples are recorded in {os.path.join(args.out, 'table_output_complete.csv')}")