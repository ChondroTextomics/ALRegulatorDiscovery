# Functions
def split_assistant(record):
  """
  Basically what we will do here will be go through each record,
  extract the assistant part of the message and then
  we will put is another part of the record
  """

  # Each record has message and metadata
  # We want the metadata ans specifically the one that has the value assistant in key role
  assistant_msgs = [
      m for m in record["messages"]
      if m.get("role") == "assistant"
    ]

  # Now we add as a feature the value for the record
  record["gold_assistant"] = assistant_msgs

  # Now we rewrite the message record so it only has system and user roles
  record["messages"] = [
      m for m in record["messages"]
      if m.get("role") != "assistant"
    ]

  return record

def formatting_prompts_func(examples):
    convos = examples["messages"]
    texts = [
        tokenizer.apply_chat_template(
                    convo, # we are giving a column if we dont do the list and the behaviour is not correct
                    tokenize = False,
                    add_generation_prompt = True,
                    enable_thinking = False # Switches between thinking and non-thinking modes. Default is True.
                    )
        for convo in convos
    ]
    return {"prompt": texts}

